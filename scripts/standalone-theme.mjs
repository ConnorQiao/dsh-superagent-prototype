#!/usr/bin/env node
// Writes src/client/standalone-theme.css: the DSH design tokens the panel's stylesheet reads (`--dsw-*`, `--ds-*`), for a page
// that shows the panel outside DeepSeek Harness (`src/client/standalone.tsx`) and so has no DSH theme of its own. They come
// from @deepseek-ai/dsh-client-ui-theme (MIT), light theme only, moved from `body` to `:root` so that what the panel portals
// to the page's body (toasts, dialogs) reads them too.
//
// Usage: node scripts/standalone-theme.mjs <the dsh-client-ui-theme package directory>
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) { console.error('usage: node scripts/standalone-theme.mjs <dsh-client-ui-theme package directory>'); process.exit(2) }
const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
/** The custom properties of every rule whose selector is exactly one of `selectors`, in order. */
function properties(file, selectors) {
  const css = readFileSync(join(dir, 'src/styles', file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  const out = []
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!selectors.includes(match[1].replace(/\s+/g, ' ').trim())) continue
    for (const declaration of match[2].split(';')) {
      const line = declaration.trim()
      if (line.startsWith('--')) out.push(line.replace(/\s+/g, ' '))
    }
  }
  return out
}
// base.css defines the font and radius variables on :root and refines the font stacks on body; the colors and shadows are on
// body, and the elevations on every element, so that each resolves them against the stroke color it sees.
const named = lines => new Map(lines.map(line => [line.slice(0, line.indexOf(':')).trim(), line]))
const inherited = named([...properties('base.css', [':root', 'body']), ...properties('design-platform.css', ['body']),
  ...properties('gradient-shadow-text.css', ['body'])])
const each = named(properties('gradient-shadow-text.css', ['body, body *']))
const header = `/* Generated by scripts/standalone-theme.mjs from ${pkg.name} ${pkg.version} (MIT, https://github.com/deepseek-ai/deepseek-harness): the DSH light-theme tokens for the panel outside DeepSeek Harness. Do not edit by hand. */`
const rule = (selector, values) => `${selector} { ${[...values.values()].join('; ')}; }`
writeFileSync(new URL('../src/client/standalone-theme.css', import.meta.url),
  `${header}\n${rule(':root', inherited)}\n${rule(':root, :root *', each)}\n`)
console.log(`src/client/standalone-theme.css: ${inherited.size + each.size} properties from ${pkg.name} ${pkg.version}`)
